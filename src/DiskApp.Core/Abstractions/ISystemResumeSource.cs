namespace DiskApp.Core.Abstractions;

/// <summary>
/// Сообщает о выходе компьютера из сна (PLAN.md, этап 10.3). Пока он спал, съёмные и сетевые диски могли отключиться,
/// а наблюдатели — пропустить изменения, поэтому после пробуждения корни индекса проверяются заново.
/// </summary>
public interface ISystemResumeSource
{
    /// <summary>
    /// Подписаться на пробуждение. Обработчик вызывается в пуле потоков и не должен бросать исключения;
    /// освобождение результата отменяет подписку.
    /// </summary>
    IDisposable Subscribe(Action onResumed);
}
